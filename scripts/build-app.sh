#!/bin/zsh
# Builds Voxara.app, signs it with the local identity and installs it to ~/Applications.
# Usage: scripts/build-app.sh [--no-install] [--debug]
set -euo pipefail
cd "$(dirname "$0")/.."

CONFIG=release
INSTALL=1
for arg in "$@"; do
  case $arg in
    --no-install) INSTALL=0 ;;
    --debug) CONFIG=debug ;;
  esac
done

APP_NAME=Voxara
BUNDLE_ID=com.daniel.voicetext
IDENTITY="VoiceText Local Signing"
VERSION=0.1.0
BUILD_NUMBER=$(git rev-list --count HEAD 2>/dev/null || echo 1)

swift build -c "$CONFIG" --product "$APP_NAME" 2>&1 | grep -v "search path" | grep -E "error|warning: |Build complete" || true
BIN_DIR=$(swift build -c "$CONFIG" --show-bin-path)
[[ -x "$BIN_DIR/$APP_NAME" ]] || { echo "Build failed"; exit 1; }

APP="build/$APP_NAME.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/$APP_NAME" "$APP/Contents/MacOS/$APP_NAME"
# SwiftPM resource bundles; Bundle.module looks in Contents/Resources first.
for bundle in "$BIN_DIR"/*.bundle; do
  [[ "$(basename "$bundle")" == *Tests.bundle ]] && continue
  cp -R "$bundle" "$APP/Contents/Resources/"
done

# Brand assets: app icon and menu-bar template glyph (generated by scripts/make-icon.sh).
[[ -f Brand/icons/Voxara.icns ]] && cp Brand/icons/Voxara.icns "$APP/Contents/Resources/Voxara.icns"
cp Brand/icons/menubar-template*.png "$APP/Contents/Resources/" 2>/dev/null || true

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleExecutable</key><string>$APP_NAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleIconFile</key><string>Voxara</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$BUILD_NUMBER</string>
  <key>LSMinimumSystemVersion</key><string>15.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSSupportsAutomaticTermination</key><false/>
  <key>NSSupportsSuddenTermination</key><false/>
  <key>NSMicrophoneUsageDescription</key><string>Voxara records your voice while you hold the dictation shortcut and transcribes it on this Mac.</string>
</dict>
</plist>
PLIST

cat > build/entitlements.plist <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>com.apple.security.device.audio-input</key><true/>
</dict>
</plist>
PLIST

if security find-identity -v -p codesigning | grep -q "$IDENTITY"; then
  SIGN_AS="$IDENTITY"
else
  echo "warning: '$IDENTITY' not found (run scripts/create-signing-cert.sh); ad-hoc signing — permissions will reset on every rebuild"
  SIGN_AS="-"
fi
codesign --force --deep --options runtime --timestamp=none \
  --entitlements build/entitlements.plist --sign "$SIGN_AS" "$APP"
codesign --verify --strict "$APP"
echo "Built $APP ($CONFIG, build $BUILD_NUMBER)"

if [[ $INSTALL == 1 ]]; then
  DEST="$HOME/Applications/$APP_NAME.app"
  pkill -x "$APP_NAME" 2>/dev/null && sleep 0.5 || true
  # Retire the pre-rename build so two copies never listen for the same hotkeys.
  if [[ -d "$HOME/Applications/VoiceText.app" ]]; then
    pkill -x VoiceText 2>/dev/null && sleep 0.5 || true
    rm -rf "$HOME/Applications/VoiceText.app"
    echo "Removed legacy ~/Applications/VoiceText.app"
  fi
  mkdir -p "$HOME/Applications"
  rm -rf "$DEST"
  cp -R "$APP" "$DEST"
  echo "Installed to $DEST"
  # The staging copy would show up as a second "Voxara" in Spotlight and Launchpad; the installed one is the real app.
  rm -rf "$APP"
fi
