import AppKit

/// Full copy of every item and every type on a pasteboard, so the user's clipboard
/// (text, images, files, rich text) can be restored exactly after a paste.
public struct PasteboardSnapshot: @unchecked Sendable {
    public let items: [[NSPasteboard.PasteboardType: Data]]

    public static func capture(_ pasteboard: NSPasteboard = .general) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
        return PasteboardSnapshot(items: items)
    }

    public func restore(to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { entry in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}

extension NSPasteboard.PasteboardType {
    /// nspasteboard.org conventions: clipboard managers skip transient/auto-generated content.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let voiceTextMarker = NSPasteboard.PasteboardType("com.daniel.voicetext.generated")
}

extension NSPasteboard {
    /// Writes text marked as transient so clipboard history tools ignore it.
    /// Returns the resulting change count.
    @discardableResult
    func writeTransientText(_ text: String) -> Int {
        clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: .transient)
        item.setData(Data(), forType: .autoGenerated)
        item.setData(Data(), forType: .voiceTextMarker)
        writeObjects([item])
        return changeCount
    }

    /// Writes text the user should keep (e.g. after a failed insertion).
    @discardableResult
    public func writePlainText(_ text: String) -> Int {
        clearContents()
        setString(text, forType: .string)
        return changeCount
    }
}
